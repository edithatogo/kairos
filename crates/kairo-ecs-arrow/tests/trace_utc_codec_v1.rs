use kairo_ecs_arrow::trace_time::utc_codec::{
    check_utc_companion, decode_utc_nanoseconds, encode_utc_nanoseconds, format_canonical_utc,
    parse_canonical_utc, UtcCodecError,
};

#[test]
fn binary_encoding_is_lossless_and_little_endian_across_signed_domain() {
    let mut min = [0u8; 16];
    min[15] = 0x80;
    let mut max = [0xffu8; 16];
    max[15] = 0x7f;
    let mut one = [0u8; 16];
    one[0] = 1;
    for (value, bytes) in [
        (i128::MIN, min),
        (i128::MAX, max),
        (-1, [0xff; 16]),
        (0, [0; 16]),
        (1, one),
    ] {
        assert_eq!(encode_utc_nanoseconds(value), bytes);
        assert_eq!(decode_utc_nanoseconds(&bytes), Ok(value));
    }
    for bytes in [&[][..], &[0u8; 15][..], &[0u8; 17][..]] {
        assert_eq!(
            decode_utc_nanoseconds(bytes),
            Err(UtcCodecError::InvalidByteLength)
        );
    }
}
#[test]
fn epoch_and_negative_fraction_have_independent_exact_text() {
    for (value, text) in [
        (0, "1970-01-01T00:00:00.000000000Z"),
        (1, "1970-01-01T00:00:00.000000001Z"),
        (-1, "1969-12-31T23:59:59.999999999Z"),
        (-1000000000, "1969-12-31T23:59:59.000000000Z"),
    ] {
        assert_eq!(format_canonical_utc(value), Ok(text.to_owned()));
        assert_eq!(parse_canonical_utc(text), Ok(value));
        assert_eq!(
            check_utc_companion(&encode_utc_nanoseconds(value), text),
            Ok(value)
        );
    }
}
#[test]
fn text_bounds_reject_outside_without_narrowing_binary_domain() {
    for (value, text) in [
        (-62135596800000000000i128, "0001-01-01T00:00:00.000000000Z"),
        (253402300799999999999, "9999-12-31T23:59:59.999999999Z"),
    ] {
        assert_eq!(format_canonical_utc(value), Ok(text.to_owned()));
        assert_eq!(parse_canonical_utc(text), Ok(value));
    }
    for value in [
        i128::MIN,
        i128::MAX,
        -62135596800000000001,
        253402300800000000000,
    ] {
        assert_eq!(
            format_canonical_utc(value),
            Err(UtcCodecError::OutOfTextRange)
        );
        assert_eq!(
            decode_utc_nanoseconds(&encode_utc_nanoseconds(value)),
            Ok(value)
        );
    }
    assert_eq!(
        parse_canonical_utc("0000-01-01T00:00:00.000000000Z"),
        Err(UtcCodecError::OutOfTextRange)
    );
}
#[test]
fn invalid_calendar_and_leap_seconds_never_fold_or_normalize() {
    for text in [
        "1900-02-29T00:00:00.000000000Z",
        "2100-02-29T00:00:00.000000000Z",
        "2001-02-29T00:00:00.000000000Z",
        "2000-02-30T00:00:00.000000000Z",
        "2000-00-01T00:00:00.000000000Z",
        "2000-13-01T00:00:00.000000000Z",
        "2000-01-00T00:00:00.000000000Z",
        "2000-01-32T00:00:00.000000000Z",
        "2000-01-01T24:00:00.000000000Z",
        "2000-01-01T00:60:00.000000000Z",
        "2000-01-01T00:00:60.000000000Z",
    ] {
        assert_eq!(
            parse_canonical_utc(text),
            Err(UtcCodecError::InvalidCalendar),
            "{text}"
        );
    }
    assert_eq!(
        parse_canonical_utc("2000-02-29T00:00:00.000000000Z"),
        Ok(951782400000000000)
    );
    assert_eq!(
        parse_canonical_utc("2004-02-29T00:00:00.000000000Z"),
        Ok(1078012800000000000)
    );
}
#[test]
fn noncanonical_text_is_rejected_without_permissive_source_parsing() {
    for text in [
        "1970-01-01T00:00:00Z",
        "1970-01-01T00:00:00.00000000Z",
        "1970-01-01T00:00:00.0000000000Z",
        "1970-01-01T00:00:00.000000000+00:00",
        "1970-01-01t00:00:00.000000000Z",
        "1970-01-01T00:00:00.000000000z",
        " 1970-01-01T00:00:00.000000000Z",
        "1970-01-01T00:00:00.000000000Z ",
        "+1970-01-01T00:00:00.000000000Z",
        "10000-01-01T00:00:00.000000000Z",
        "１９７０-01-01T00:00:00.000000000Z",
        "1970/01-01T00:00:00.000000000Z",
    ] {
        assert_eq!(
            parse_canonical_utc(text),
            Err(UtcCodecError::NoncanonicalText),
            "{text}"
        );
    }
}
#[test]
fn companions_require_exact_agreement_and_fixed_rejection_precedence() {
    let zero = [0u8; 16];
    let mut one = [0u8; 16];
    one[0] = 1;
    assert_eq!(
        check_utc_companion(&one, "1970-01-01T00:00:00.000000000Z"),
        Err(UtcCodecError::CompanionMismatch)
    );
    assert_eq!(
        check_utc_companion(&zero, "1970-01-01T00:00:00.000000001Z"),
        Err(UtcCodecError::CompanionMismatch)
    );
    assert_eq!(
        check_utc_companion(&[0u8; 15], "not utc"),
        Err(UtcCodecError::InvalidByteLength)
    );
    assert_eq!(
        check_utc_companion(&zero, "not utc"),
        Err(UtcCodecError::NoncanonicalText)
    );
    let error: &dyn std::error::Error = &UtcCodecError::CompanionMismatch;
    assert!(!error.to_string().is_empty());
    assert!(error.source().is_none());
}
