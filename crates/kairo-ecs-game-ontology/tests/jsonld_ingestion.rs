use kairo_ecs_game_ontology::parse_jsonld; 
 
#[test] 
fn parses_jsonld_classes_and_properties() { 
    let bytes = [ 
        123,10,32,32,34,105,100,34,58,32,34,103,116,58,71,97,109,101,34,44,10,32,32,34,116,121,112,101,34,58,32,34,114,100,102,115,58,67,108,97,115,115,34,10,125,44,10, 
        123,10,32,32,34,105,100,34,58,32,34,103,116,58,104,97,115,80,108,97,121,101,114,34,44,10,32,32,34,116,121,112,101,34,58,32,34,114,100,102,115,58,80,114,111,112,101,114,116,121,34,44,10,32,32,34,114,100,102,115,58,100,111,109,97,105,110,34,58,32,34,103,116,58,71,97,109,101,34,44,10,32,32,34,114,100,102,115,58,114,97,110,103,101,34,58,32,34,103,116,58,80,108,97,121,101,114,34,10,125,10, 
    ]; 
    let text = std::str::from_utf8(&bytes).unwrap(); 
    let doc = parse_jsonld(text).unwrap(); 
    assert_eq!(doc.classes.len(), 1); 
    assert_eq!(doc.properties.len(), 1); 
    assert_eq!(doc.classes[0].id.as_bytes(), &[103,116,58,71,97,109,101]); 
    assert_eq!(doc.properties[0].id.as_bytes(), &[103,116,58,104,97,115,80,108,97,121,101,114]); 
}
